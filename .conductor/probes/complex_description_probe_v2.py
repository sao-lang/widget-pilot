def e2e(desc: str, grid: str = "2x2") -> str:
    try:
        r = raw(
            "probe-s", "probe-r", desc, grid, [], "WIDGET_GENERATION", 100.0,
            hit_store=InMemoryGuardHitStore(),
            route_log=IntentRouteLogStore(),
            audit_store=InMemoryAuditStore(),
        )
        return f"ok={r.ok} reason={r.reason_code.value if r.reason_code else '-'}"
    except Exception as exc:  # noqa: BLE001
        return f"EXC={type(exc).__name__}:{str(exc)[:60]}"


def main() -> None:
    itp = RuleInterpreter()
    for case in CASES:
        cid, cover, desc = case[0], case[1], case[2]
        mix = classify_intent_mix(desc)
        g = check_input(desc, [], IntentCategory.WIDGET_GENERATION.value, Budget())
        r = itp.interpret(desc)
        slots = r.instances[0].slots if r.instances else {}
        print(f"\n[{cid} {cover}] {len(desc)}字: {desc[:70]}…")
        print(f"  classify={mix[0]} segs={len(mix[1])} check={g.passed}/{[h.rule_id for h in g.hits]}")
        print(f"  itp={r.kind} n={len(r.instances)} miss={r.missing_slots} intent={[i.intent_id for i in r.instances][:3]}")
        print(f"  slots={sorted(k for k in slots if k in ('grid','data','host','count','style','interaction','function','structure','attachment_purpose','target'))}")
        print(f"  e2e: {e2e(desc)}")


if __name__ == "__main__":
    main()
